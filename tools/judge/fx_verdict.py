"""Приговор по одному узлу цепи: сошлось или нет.

Отделено от `check_effects.sh` затем, что сравнение чисел с порогом в bash
пишется плохо, а без сравнения гейт бесполезен.

🔴 ЧТО ЗДЕСЬ БЫЛО СЛОМАНО. Прежний `check_effects.sh` числа только ПЕЧАТАЛ:
`fail` рос ровно в одном месте — когда плагин не создал файл, а отсутствие
эталона печаталось «пропущен» и провалом не считалось. Гейт выходил нулём и
при расхождении в шесть децибел, и на свежем клоне, где эталонов нет вовсе:
сорок один замер, ноль сравнений, зелено. Заявка «расхождение по СКЗ до сотых
долей децибела» держалась на том, что человек посмотрел глазами в таблицу.

    python tools/judge/fx_verdict.py <id> <СКЗ> <пик> <худшая полоса>

Печатает `сошлось` либо `ВЫШЕ ПОРОГА: …` и выходит 0 или 1.
"""

import sys

# Общий порог: столько расходятся узлы, у которых расхождению взяться неоткуда.
LIMIT = {"rms": 0.10, "peak": 1.00, "band": 3.00}

# 🔴 ИМЕНОВАННЫЕ ПОСЛАБЛЕНИЯ — по одному на причину, и КАЖДОЕ с причиной.
# Это не «подгон под текущее»: сюда попадает только то, у чего причина названа.
# Цифра — предел, а не замер: замер обязан лежать ВНУТРИ него с запасом.
EXCEPT = {
    # 🔴 СПИСОК УСОХ ДО ОДНОЙ СТРОКИ, И ЭТО НЕ ПОДГОН ПОРОГОВ.
    #
    # Здесь было девять записей: треугольник −9.75 в полосе, перегруз Чебышёва
    # −7.71, `lpf_low` +7.88, `penv` −5.78, оба порядка `crush`/`lpf` по −4.83.
    # Пять из них `docs/COMPARISON.md` объявлял неустранимыми свойствами узлов,
    # четыре стояли «долгом без разобранной причины». Причина у всех оказалась
    # ОДНА: без `partials` играть надо ШТАТНОЙ волной WebAudio, а порт всегда
    # строил таблицу по коэффициентам `waveformN`, у которых другая начальная
    # фаза. После починки те же узлы дают +0.03, +0.06, +0.09, +0.01 и −1.76.
    "compressor": ({"rms": 0.70, "peak": 2.20, "band": 8.0},
                   "следящий узел сжатия устроен иначе — схема названа в COMPARISON.md"),
}

# 🔴 УЗЛЫ, КОТОРЫЕ ЧИСЛОМ НЕ СВЕРИТЬ — и это не то же самое, что «сошлись».
#
# У стаи пил начальные фазы голосов СЛУЧАЙНЫ, и так же в оригинале
# (`worklets.mjs`, `Math.random()`). Пять близких частот складываются то в лад,
# то врозь, и уровень гуляет от прогона к прогону: замерено СКЗ +0.24, +0.77,
# +1.02, полоса −4.74, −9.31, −10.88, −16.12. Никакой порог тут ничего не
# проверяет — он либо ловит собственный шум узла, либо, если его раздвинуть под
# худший случай, пропускает настоящую поломку.
#
# Поэтому такие узлы считаются ОТДЕЛЬНО и в число сверенных НЕ входят: иначе
# строка «сверено 41» врёт про два из них.
UNGATED = {
    "supersaw": "фазы пил случайны и в оригинале — разброс до 1.0 дБ по СКЗ и 16 дБ в полосе",
    "supersaw_wide": "то же, стая шире",
}


def main() -> int:
    if len(sys.argv) < 5:
        print("нужно: id скз пик полоса")
        return 2
    node = sys.argv[1]
    if node in UNGATED:
        # Код 2 — «не сверялся»: не провал и не совпадение.
        print("НЕ СВЕРЯЕТСЯ ЧИСЛОМ: " + UNGATED[node])
        return 2
    limits = dict(LIMIT)
    why = ""
    if node in EXCEPT:
        extra, why = EXCEPT[node]
        limits.update(extra)

    bad = []
    for key, raw in (("rms", sys.argv[2]), ("peak", sys.argv[3]), ("band", sys.argv[4])):
        text = (raw or "").strip()
        if text == "":
            # Пустое поле значит, что сравнение не состоялось. Это провал, а не
            # «ноль»: молчание нельзя считать совпадением.
            bad.append("%s не измерен" % key)
            continue
        try:
            value = abs(float(text))
        except ValueError:
            bad.append("%s не число (%s)" % (key, text))
            continue
        if value > limits[key]:
            bad.append("%s %.2f > %.2f" % (key, value, limits[key]))

    if bad:
        print("ВЫШЕ ПОРОГА: " + ", ".join(bad))
        return 1
    print("сошлось" + (" (послабление: %s)" % why if why else ""))
    return 0


sys.exit(main())
